#!/bin/bash
set -e

GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo "=========================================="
echo "📦 最終コミット準備"
echo "=========================================="

# ====================================================================
# STEP 1: ステータス確認
# ====================================================================
echo ""
echo -e "${BLUE}[STEP 1/4] Git状態確認${NC}"
echo "=========================================="

git status --short

# ====================================================================
# STEP 2: 重要なファイルのみステージング
# ====================================================================
echo ""
echo -e "${BLUE}[STEP 2/4] ステージング${NC}"
echo "=========================================="

# 重要な変更のみ
git add .gitignore
git add browser_control/browser_controller.py
git add docs/

# スクリプト
git add setup_xvfb.sh
git add setup_headless_mode.sh
git add diagnose_display_environment.sh
git add fix_novnc_submodule.sh
git add final_test_run.sh

echo "✅ ステージング完了"

# ====================================================================
# STEP 3: コミット
# ====================================================================
echo ""
echo -e "${BLUE}[STEP 3/4] コミット${NC}"
echo "=========================================="

echo ""
echo "ステージングされたファイル:"
git diff --cached --name-only

echo ""
read -p "コミットしますか？ (y/n): " do_commit

if [ "$do_commit" = "y" ]; then
    git commit -m "fix: ディスプレイ環境完全対応

🔧 主な変更:
- Xvfb セットアップスクリプト追加
- ヘッドレスモード対応
- noVNCサブモジュール問題修正
- ディスプレイ環境診断ツール追加

✅ 動作確認:
- Xvfb起動成功（:1ディスプレイ）
- BrowserController ヘッドレスモード対応
- 環境診断ツールによる自動判定"

    echo -e "${GREEN}✅ コミット完了${NC}"
    
    # ====================================================================
    # STEP 4: Push
    # ====================================================================
    echo ""
    echo -e "${BLUE}[STEP 4/4] Push${NC}"
    echo "=========================================="
    
    read -p "リモートにpushしますか？ (y/n): " do_push
    
    if [ "$do_push" = "y" ]; then
        git push origin v1.0.0-integrated
        echo -e "${GREEN}✅ push完了${NC}"
    fi
else
    echo "コミットをスキップしました"
fi

echo ""
echo "=========================================="
echo -e "${GREEN}✅ 完了${NC}"
echo "=========================================="

