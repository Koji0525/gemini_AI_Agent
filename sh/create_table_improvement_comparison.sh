### 案2: カラム表示切り替え ⭐⭐⭐⭐

#### 概要
- 重要なカラムのみデフォルト表示
- 「カラム表示設定」ボタンで表示/非表示を切り替え

#### ビジュアル
```
[☑️ カラム表示設定]
┌────────────────────────────┐
│ ✅ id                      │
│ ✅ title                   │
│ ✅ created_at              │
│ ☑️ content                 │
│ ☑️ category                │
│ ☑️ tags                    │
│ ☑️ embedding               │
│ ☑️ vector_synced           │
│                            │
│ [適用]  [リセット]         │
└────────────────────────────┘

表示:
┌───┬─────┬──────────────┬────────────┬────┐
│☑️ │ id  │ title        │created_at  │操作│
└───┴─────┴──────────────┴────────────┴────┘
```

#### 実装方法
```javascript
// カラム表示設定
const columnSettings = {
    'id': true,
    'title': true,
    'content': false,  // デフォルト非表示
    'category': false,
    'tags': false,
    'embedding': false,
    'vector_synced': false,
    'created_at': true
};

// 表示切り替え
function toggleColumn(columnName) {
    document.querySelectorAll(`[data-column="${columnName}"]`)
        .forEach(cell => {
            cell.style.display = 
                columnSettings[columnName] ? 'table-cell' : 'none';
        });
}
```

#### メリット
- ✅ ユーザーが自由にカスタマイズできる
- ✅ 画面幅を有効活用
- ✅ 横スクロール不要になる
- ✅ 設定を保存できる（localStorage）

#### デメリット
- ⚠️ 初回は設定が必要
- ⚠️ 非表示のカラムが見えない（当然だが）
- ⚠️ 実装が複雑（JavaScript必要）

#### 実装難易度
⭐⭐⭐⭐ (JavaScript + localStorage、3-4時間)

